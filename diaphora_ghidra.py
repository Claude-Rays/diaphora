  # Features extraction
  #-----------------------------------------------------------------------------
  def constant_filter(self, value):
    """Filter for certain constants/immediate values. Not all values should be
    taken into account for searching. Especially not very small values that may
    just contain the stack frame size.
    """
    # no small values
    if value < 0x1000:
      return False

    if (
      value & 0xFFFFFF00 == 0xFFFFFF00
      or value & 0xFFFF00 == 0xFFFF00
      or value & 0xFFFFFFFFFFFFFF00 == 0xFFFFFFFFFFFFFF00
      or value & 0xFFFFFFFFFFFF00 == 0xFFFFFFFFFFFF00
    ):
      return False

    # no single bits sets - mostly defines / flags
    for i in range(64):
      if value == (1 << i):
        return False

    return True

  def get_disasm(self, ins):
    mnem = str(self.cuf.getMnemonicRepresentation(ins))
    operands = []
    for i in range(ins.getNumOperands()):
      operands.append(str(self.cuf.getOperandRepresentationString(ins, i)))

    line = mnem
    if len(operands) > 0:
      line = f"{mnem.ljust(7)} {','.join(operands)}"

    comment = ins.getComment(CommentType.EOL)
    if comment is not None and comment != "":
      line += f" ; {comment.splitlines()[0]}"
    return translate_ghidra_names(line)

  def get_masked_bytes(self, ins, raw):
    """
    Return the bytes of the instruction @ins without the values of operands
    (immediate values, displacements, addresses, etc...). This is the Ghidra
    equivalent of what diaphora_ida's get_decoded_instruction() does.
    """
    try:
      mask = ins.getPrototype().getInstructionMask()
      if mask is None:
        return raw
      mask_bytes = bytes(mask.getBytes())
    except:
      return raw

    ret = bytearray(len(raw))
    for i in range(min(len(raw), len(mask_bytes))):
      ret[i] = raw[i] & mask_bytes[i]
    return bytes(ret)

  def get_mnemonic_prime(self, mnem):
    """
    Ghidra has no API to get the list of instructions of a processor, so the
    prime assigned to each mnemonic is derived from its CRC32 instead.
    """
    return self.primes[zlib.crc32(mnem.encode("utf-8")) % 4096]

  def extract_function_callers(self, func):
    # Calculate the callers *but* considering data references to functions from
    # functions as code references.
    callers = []
    for ref in self.refman.getReferencesTo(func.getEntryPoint()):
      caller_func = self.funcman.getFunctionContaining(ref.getFromAddress())
      if caller_func is not None:
        caller_ea = caller_func.getEntryPoint().getUnsignedOffset()
        if caller_ea not in callers:
          callers.append(caller_ea)
    return callers

  def get_code_refs_to_count(self, func):
    """
    Return the number of code references to the function, including the
    ordinary flow (the equivalent of IDA's len(CodeRefsTo(ea, 1))).
    """
    entry = func.getEntryPoint()
    total = 0
    for ref in self.refman.getReferencesTo(entry):
      if ref.getReferenceType().isFlow():
        total += 1

    prev = self.listing.getInstructionBefore(entry)
    if prev is not None:
      fall = prev.getFallThrough()
      if fall is not None and fall.equals(entry):
        total += 1
    return total

  def get_flow_chart(self, func):
    """
    Return the list of basic blocks of the function, with the entry block first,
    as a list of dictionaries with the start address, the block object and both
    the successors and the predecessors inside the function.
    """
    body = func.getBody()
    entry = func.getEntryPoint()
    blocks = {}
    it = self.block_model.getCodeBlocksContaining(body, self.monitor)
    while it.hasNext():
      block = it.next()
      start = block.getFirstStartAddress().getUnsignedOffset()
      blocks[start] = {"start": start, "block": block, "succs": [], "preds": []}

    for start, item in blocks.items():
      dests = item["block"].getDestinations(self.monitor)
      while dests.hasNext():
        ref = dests.next()
        if ref.getFlowType().isCall():
          continue

        dest = ref.getDestinationAddress()
        if not body.contains(dest):
          continue

        dest_ea = dest.getUnsignedOffset()
        if dest_ea not in blocks:
          dest_block = self.block_model.getFirstCodeBlockContaining(dest, self.monitor)
          if dest_block is None:
            continue
          dest_ea = dest_block.getFirstStartAddress().getUnsignedOffset()
          if dest_ea not in blocks:
            continue

        if dest_ea not in item["succs"]:
          item["succs"].append(dest_ea)
          blocks[dest_ea]["preds"].append(start)

    entry_ea = entry.getUnsignedOffset()
    keys = sorted(blocks.keys())
    if entry_ea in keys:
      keys.remove(entry_ea)
      keys.insert(0, entry_ea)
    return [blocks[key] for key in keys]

  def process_instruction(self, ins, func, image_base, block_ea, accum):
    """
    Process a single instruction and extract its features.
    """
    head = ins.getAddress()
    current_head = head.getUnsignedOffset()
    func_start = func.getEntryPoint().getUnsignedOffset()

    mnem = str(ins.getMnemonicString()).lower()
    disasm = self.get_disasm(ins)
    inst_size = ins.getLength()

    # Calculate mnemonics SPP
    mnemonics_spp_mult = self.get_mnemonic_prime(mnem)

    # Add to assembly
    assembly = accum["assembly"]
    try:
      assembly[block_ea].append([current_head - image_base, disasm])
    except KeyError:
      if accum["nodes"] == 1:
        assembly[block_ea] = [[current_head - image_base, disasm]]
      else:
        assembly[block_ea] = [
          [current_head - image_base, "loc_%x:" % current_head],
          [current_head - image_base, disasm],
        ]

    # Get instruction bytes
    raw_bytes = bytes(ins.getBytes())
    curr_bytes = self.get_masked_bytes(ins, raw_bytes)
    bytes_sum = sum(curr_bytes)

    code_refs = []
    data_refs = []
    for ref in ins.getReferencesFrom():
      to_addr = ref.getToAddress()
      if not to_addr.isMemoryAddress():
        continue

      ref_type = ref.getReferenceType()
      if ref_type.isFlow():
        if not ref_type.isFallthrough():
          code_refs.append(to_addr)
      else:
        data_refs.append(to_addr)

    # Extract the (non default) referenced name
    name_to_add = None
    tmp_name = None
    for to_addr in code_refs + data_refs:
      tmp_name = self.get_symbol_name(to_addr)
      if tmp_name is None:
        continue

      sym_name = self.get_symbol_name(to_addr, include_defaults=False)
      if sym_name is not None:
        pos = sym_name.find("(")
        if pos > -1:
          sym_name = sym_name[:pos]
        if not sym_name.startswith("sub_") and not sym_name.startswith("nullsub_"):
          name_to_add = sym_name
      break

    # Calculate callees
    callees_found = []
    calls_out = 0
    for to_addr in code_refs:
      callee_func = self.funcman.getFunctionContaining(to_addr)
      if callee_func is None or callee_func.getEntryPoint().getUnsignedOffset() != func_start:
        calls_out += 1
      if callee_func is not None and not callee_func.isExternal():
        callee_ea = callee_func.getEntryPoint().getUnsignedOffset()
        if callee_ea != func_start:
          callees_found.append(callee_ea)

    # Get type from references
    tmp_type = None
    refs = code_refs if len(code_refs) > 0 else data_refs
    for to_addr in refs:
      ref_name = self.get_symbol_name(to_addr, include_defaults=False)
      if ref_name is not None:
        tmp_name = ref_name
        tmp_type = self.get_type_at(to_addr)

    # Extract constants and strings
    constants = accum["constants"]
    data_refs_eas = {x.getUnsignedOffset() for x in data_refs}
    for i in range(ins.getNumOperands()):
      for obj in ins.getOpObjects(i):
        if isinstance(obj, Scalar):
          value = to_unsigned(obj.getUnsignedValue())
          if value not in data_refs_eas and self.constant_filter(value):
            constants.append(value)

    for to_addr in data_refs:
      if self.funcman.getFunctionContaining(to_addr) is None:
        str_constant = self.get_string_at(to_addr)
        if str_constant is not None and str_constant not in constants:
          constants.append(str_constant)

    # Get instruction comments
    ins_cmt1 = ins.getComment(CommentType.EOL)
    ins_cmt2 = ins.getComment(CommentType.REPEATABLE)

    # Ghidra's equates are the closest thing to IDA's forced operands
    operands_names = []
    for i in range(ins.getNumOperands()):
      for equate in self.equates.getEquates(head, i):
        operands_names.append([i, str(equate.getDisplayName())])

    # Features used to calculate the Koret-Karamitas hash
    if ins.getFlowType().isCall():
      accum["kgh_hash"] *= KGH_FEATURE_CALL
    if len(data_refs) > 0:
      accum["kgh_hash"] *= KGH_FEATURE_DATA_REFS
    accum["kgh_hash"] *= KGH_FEATURE_CALL_REF ** calls_out

    return {
      "mnem": mnem,
      "disasm": disasm,
      "size": inst_size,
      "mnemonics_spp_mult": mnemonics_spp_mult,
      "curr_bytes": curr_bytes,
      "bytes_sum": bytes_sum,
      "function_hash_bytes": raw_bytes,
      "outdegree_inc": len(code_refs),
      "name_to_add": name_to_add,
      "callees_found": callees_found,
      "tmp_name": tmp_name,
      "tmp_type": tmp_type,
      "ins_cmt1": ins_cmt1,
      "ins_cmt2": ins_cmt2,
      "operands_names": operands_names,
    }

  def process_basic_block(self, block, func, image_base, accum):
    """ Process one basic block and its instructions
    """
    accum["nodes"] += 1
    instructions_data = []

    block_ea = block["start"] - image_base
    idx = len(accum["bb_topological"])
    accum["bb_topological"][idx] = []
    accum["bb_topo_num"][block_ea] = idx

    succs = block["succs"]
    preds = block["preds"]
    accum["kgh_hash"] *= self.get_kgh_node_value(len(succs), len(preds))
    accum["kgh_hash"] *= KGH_EDGE_OUT_CONDITIONAL ** len(succs)
    accum["kgh_hash"] *= KGH_EDGE_IN_CONDITIONAL ** len(preds)

    current_head = None
    for ins in self.listing.getInstructions(block["block"], True):
      current_head = ins.getAddress().getUnsignedOffset()
      inst_data = self.process_instruction(ins, func, image_base, block_ea, accum)

      # Update accumulators
      accum["size"] += inst_data["size"]
      accum["instructions"] += 1
      accum["mnemonics_spp"] *= inst_data["mnemonics_spp_mult"]
      accum["bytes_hash"].append(inst_data["curr_bytes"])
      accum["bytes_sum"] += inst_data["bytes_sum"]
      accum["function_hash"].append(inst_data["function_hash_bytes"])
      accum["outdegree"] += inst_data["outdegree_inc"]
      accum["mnems"].append(inst_data["mnem"])

      if inst_data["name_to_add"]:
        accum["names"].add(inst_data["name_to_add"])

      for callee_ea in inst_data["callees_found"]:
        if callee_ea not in accum["callees"]:
          accum["callees"].append(callee_ea)

      # Build instruction data entry
      instructions_data.append([
        current_head - image_base,
        inst_data["mnem"],
        inst_data["disasm"],
        inst_data["ins_cmt1"],
        inst_data["ins_cmt2"],
        inst_data["operands_names"],
        inst_data["tmp_name"],
        inst_data["tmp_type"],
      ])

    if current_head is not None:
      accum["current_head"] = current_head

    # Store basic block data
    accum["basic_blocks_data"][block_ea] = instructions_data
    accum["bb_relations"][block_ea] = []
    if block_ea not in accum["bb_degree"]:
      accum["bb_degree"][block_ea] = [0, 0]

    # Process successor blocks
    for succ_ea in succs:
      succ_base = succ_ea - image_base
      accum["bb_relations"][block_ea].append(succ_base)
      accum["bb_degree"][block_ea][1] += 1
      accum["bb_edges"].append((block_ea, succ_base))
      if succ_base not in accum["bb_degree"]:
        accum["bb_degree"][succ_base] = [0, 0]
      accum["bb_degree"][succ_base][0] += 1

      accum["edges"] += 1
      accum["indegree"] += 1

    # Process predecessor blocks (yes, edges are counted twice, as in IDA)
    for pred_ea in preds:
      try:
        accum["bb_relations"][pred_ea - image_base].append(block_ea)
      except KeyError:
        accum["bb_relations"][pred_ea - image_base] = [block_ea]

      accum["edges"] += 1
      accum["outdegree"] += 1

    return accum

  def build_topological_relations(self, flow, image_base, bb_topo_num, bb_topological):
    """ Build topological relationships between basic blocks
    """
    for block in flow:
      block_ea = block["start"] - image_base
      for succ_ea in block["succs"]:
        succ_base = succ_ea - image_base
        bb_topological[bb_topo_num[block_ea]].append(bb_topo_num[succ_base])
    return bb_topological

  def get_kgh_node_value(self, succs, preds):
    ret = 1
    if preds == 0:
      ret *= KGH_NODE_ENTRY
    if succs == 0:
      ret *= KGH_NODE_EXIT
    ret *= KGH_NODE_NORMAL
    return ret

  def calculate_kgh_hash(self, accum, flow, flags):
    """
    Finish the calculation of the Koret-Karamitas hash, whose per basic block
    and per instruction parts were calculated while processing the function.
    """
    kgh_hash = accum["kgh_hash"]
    bb_relations = {}
    for block in flow:
      bb_relations[block["start"]] = list(block["succs"])

    try:
      strongly_connected = strongly_connected_components(bb_relations)
      for sc in strongly_connected:
        if len(sc) > 1 or (sc[0] in bb_relations and sc[0] in bb_relations[sc[0]]):
          kgh_hash *= KGH_FEATURE_LOOP
      kgh_hash *= KGH_FEATURE_STRONGLY_CONNECTED ** len(strongly_connected)
    except RecursionError:
      pass

    if flags & FUNC_NORET:
      kgh_hash *= KGH_FEATURE_FUNC_NO_RET
    if flags & FUNC_LIB:
      kgh_hash *= KGH_FEATURE_FUNC_LIB
    if flags & FUNC_THUNK:
      kgh_hash *= KGH_FEATURE_FUNC_THUNK
    return str(kgh_hash)

  def extract_function_mdindex(
    self, bb_topological, bb_topological_sorted, bb_edges, bb_topo_num, bb_degree
  ):
    md_index = 0
    if bb_topological:
      bb_topo_order = {}
      for i, scc in enumerate(bb_topological_sorted):
        for bb in scc:
          bb_topo_order[bb] = i
      tuples = []
      for src, dst in bb_edges:
        tuples.append(
          (
            bb_topo_order[bb_topo_num[src]],
            bb_degree[src][0],
            bb_degree[src][1],
            bb_degree[dst][0],
            bb_degree[dst][1],
          )
        )
      rt2, rt3, rt5, rt7 = (decimal.Decimal(p).sqrt() for p in (2, 3, 5, 7))
      emb_tuples = (
        sum((z0, z1 * rt2, z2 * rt3, z3 * rt5, z4 * rt7))
        for z0, z1, z2, z3, z4 in tuples
      )
      md_index = sum(1 / emb_t.sqrt() for emb_t in emb_tuples)
      md_index = str(md_index)
    return md_index

  def extract_function_pseudocode_features(self, f):
    pseudo = None
    pseudo_hash1 = None
    pseudo_hash2 = None
    pseudo_hash3 = None
    pseudo_lines = 0
    pseudocode_primes = None
    if f in self.pseudo:
      pseudo = "\n".join(self.pseudo[f])
      pseudo_lines = len(self.pseudo[f])
      pseudo_hash1, pseudo_hash2, pseudo_hash3 = self.kfh.hash_bytes(
        pseudo
      ).split(";")
      if pseudo_hash1 == "":
        pseudo_hash1 = None
      if pseudo_hash2 == "":
        pseudo_hash2 = None
      if pseudo_hash3 == "":
        pseudo_hash3 = None
      pseudocode_primes = str(self.pseudo_hash[f])
    return (
      pseudo,
      pseudo_lines,
      pseudo_hash1,
      pseudocode_primes,
      pseudo_hash2,
      pseudo_hash3,
    )

  def extract_function_assembly_features(self, assembly, f, image_base):
    asm = []
    keys = list(assembly.keys())
    keys.sort()

    # Collect the ordered list of addresses, as shown in the assembly
    # viewer (when diffing). It will be extremely useful for importing
    # stuff later on.
    assembly_addrs = []

    # After sorting out the addresses of basic blocks, be sure that the
    # very first address is always the entry point, no matter at what
    # address it is.
    base = f - image_base
    if base in keys:
      keys.remove(base)
    keys.insert(0, base)
    for key in keys:
      if key not in assembly:
        continue
      for line in assembly[key]:
        assembly_addrs.append(line[0])
        asm.append(line[1])
    asm = "\n".join(asm)
    return asm, assembly_addrs

  def extract_function_topological_information(self, bb_relations, bb_topological):
    loops = 0
    strongly_connected = None
    strongly_connected_spp = 0
    bb_topological_sorted = None
    try:
      strongly_connected = strongly_connected_components(bb_relations)
      bb_topological_sorted = robust_topological_sort(bb_topological)
      bb_topological = json.dumps(bb_topological_sorted)
      strongly_connected_spp = 1
      for item in strongly_connected:
        val = len(item)
        if val > 1:
          strongly_connected_spp *= self.primes[val]
    except RecursionError:
      # XXX: FIXME: The original implementation that we're using is recursive
      # and can fail. We really need to create our own non recursive version.
      strongly_connected = []
      bb_topological = None

    loops = 0
    for sc in strongly_connected:
      if len(sc) > 1:
        loops += 1
      else:
        if sc[0] in bb_relations and sc[0] in bb_relations[sc[0]]:
          loops += 1

    return (
      bb_topological,
      bb_topological_sorted,
      strongly_connected,
      loops,
      strongly_connected_spp,
    )

  def extract_microcode(self, f):
    micro = None
    micro_spp = 1
    clean_micro = None
    if self.export_microcode and f in self.microcode:
      micro = "\n".join(self.microcode[f])
      ret = []
      for line in self.microcode[f]:
        tokens = line.split(" ")
        mnem = tokens[1] if len(tokens) > 1 else ""
        if mnem == "":
          continue

        ret.append(line[line.find(mnem):])
        if mnem in self.microcode_ins_list:
          micro_spp *= self.primes[self.microcode_ins_list.index(mnem)]
      clean_micro = self.get_cmp_asm_lines("\n".join(ret))
    return micro, clean_micro, micro_spp

