def export_and_diff(program, opts, monitor=None, chooser=diaphora.CChooser,
                    export=True, resume_crashed=False, ask_yes_no=None):
  """
  Export the program @program to the database @opts.file_out and, optionally,
  diff it against @opts.file_in. Returns the CGhidraBinDiff object.
  """
  if export and not resume_crashed and os.path.exists(opts.file_out):
    remove_file(opts.file_out)
    log(f"Database {repr(opts.file_out)} removed")

  t0 = time.monotonic()
  total_functions = program.getFunctionManager().getFunctionCount()

  bd = CGhidraBinDiff(opts.file_out, program=program, monitor=monitor, chooser=chooser)
  bd.ask_yes_no = ask_yes_no
  bd.use_decompiler = opts.use_decompiler
  bd.exclude_library_thunk = opts.exclude_library_thunk
  bd.unreliable = opts.unreliable
  bd.slow_heuristics = opts.slow
  bd.use_trained_model = opts.use_trained_model
  bd.relaxed_ratio = opts.relax
  bd.experimental = opts.experimental
  bd.ida_subs = opts.ida_subs
  bd.ignore_sub_names = opts.ignore_sub_names
  bd.ignore_all_names = opts.ignore_all_names
  bd.ignore_small_functions = opts.ignore_small_functions
  bd.function_summaries_only = opts.func_summaries_only
  bd.export_microcode = opts.export_microcode
  bd.sql_max_processed_rows = config.SQL_MAX_PROCESSED_ROWS
  bd.timeout = config.SQL_TIMEOUT_LIMIT * max(total_functions / 20000, 1)
  bd.project_script = opts.project_script

  # A string default makes get_value_for() return the raw (hexadecimal) value
  from_address = bd.get_value_for("from_address", "")
  if from_address != "":
    bd.min_ea = int(from_address, 16)
  to_address = bd.get_value_for("to_address", "")
  if to_address != "":
    bd.max_ea = int(to_address, 16)

  if export:
    if not bd.export():
      log("Error exporting the database.")
      return bd

    final_t = time.monotonic() - t0
    log(f"Database exported, time taken: {datetime.timedelta(seconds=final_t)}.")

  if opts.file_in is not None and opts.file_in != "":
    bd.diff(opts.file_in)
    if opts.results_file is not None and opts.results_file != "":
      bd.save_results(opts.results_file)

  return bd
