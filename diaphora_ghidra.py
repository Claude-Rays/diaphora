def remove_file(filename):
  try:
    os.remove(filename)
  except:
    # The file might be still opened by SQLite in Windows, just drop the tables
    # in that case and continue normally.
    with sqlite3.connect(filename, check_same_thread=False) as db:
      tables = [
        "functions", "program", "program_data", "version", "instructions",
        "basic_blocks", "bb_relations", "bb_instructions", "function_bblocks",
        "callgraph", "constants", "compilation_units", "compilation_unit_functions",
      ]
      for table in tables:
        db.execute(f"drop table if exists {table}")

  for ext in ["-wal", "-shm", "-crash"]:
    if os.path.exists(filename + ext):
      try:
        os.remove(filename + ext)
      except: # noqa: S110
        pass

