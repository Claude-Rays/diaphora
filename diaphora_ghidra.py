# IDA's function flags. Ghidra doesn't have them, so we emulate the ones that
# Diaphora uses to keep the exported databases as close as possible to the ones
# generated by the IDA exporter.
FUNC_NORET = 0x00000001
FUNC_LIB = 0x00000004
FUNC_THUNK = 0x00000080

# Prime values used by the Koret-Karamitas CFG hash (see jkutils/graph_hashes.py,
# which cannot be imported here because it depends on the IDA APIs).
KGH_NODE_ENTRY = 2
KGH_NODE_EXIT = 3
KGH_NODE_NORMAL = 5
KGH_EDGE_IN_CONDITIONAL = 7
KGH_EDGE_OUT_CONDITIONAL = 11
KGH_FEATURE_LOOP = 19
KGH_FEATURE_CALL = 23
KGH_FEATURE_DATA_REFS = 29
KGH_FEATURE_CALL_REF = 31
KGH_FEATURE_STRONGLY_CONNECTED = 37
KGH_FEATURE_FUNC_NO_RET = 41
KGH_FEATURE_FUNC_LIB = 43
KGH_FEATURE_FUNC_THUNK = 47

# Diaphora's heuristics and text cleaning routines expect IDA's names for auto
# generated symbols (sub_, loc_, off_...). Ghidra's default names are translated
# to the IDA equivalents so both the diffing engine and the databases exported
# from IDA keep working as expected.
GHIDRA_DEFAULT_PREFIXES = {
  "thunk_FUN_": "j_sub_",
  "FUN_": "sub_",
  "SUB_": "sub_",
  "LAB_": "loc_",
  "DAT_": "unk_",
  "UNK_": "unk_",
  "EXT_": "unk_",
  "BYTE_": "byte_",
  "WORD_": "word_",
  "DWORD_": "dword_",
  "QWORD_": "qword_",
  "FLOAT_": "flt_",
  "DOUBLE_": "dbl_",
  "switchD_": "jpt_",
}
_PREFIXES_ALT = "|".join(sorted(GHIDRA_DEFAULT_PREFIXES, key=len, reverse=True))
GHIDRA_DEFAULT_NAME_RE = re.compile(rf"(?<![\w])({_PREFIXES_ALT})(?=[0-9a-fA-F]+\b)")
GHIDRA_POINTER_NAME_RE = re.compile(r"(?<![\w])PTR_(?=\w)")
GHIDRA_STRING_NAME_RE = re.compile(r"(?<![\w])[su]_(\w+?)_[0-9a-fA-F]{6,16}\b")

# Ghidra specific names that change between builds and must be ignored when
# comparing assembly or pseudo-code.
GHIDRA_CLEAN_ASM_REPS = [
  (r"\blocal_res[0-9a-f]+\b", "local_XXX"),
  (r"\blocal_[0-9a-f]+(_[0-9a-f]+)?\b", "local_XXX"),
  (r"\b[a-z]*Stack_[0-9a-f]+\b", "local_XXX"),
]
GHIDRA_CLEAN_PSEUDO_REPS = [
  (r"\b[a-z]{1,5}Var[0-9]+\b", "vXXX"),
  (r"\blocal_res[0-9a-f]+\b", "vXXX"),
  (r"\blocal_[0-9a-f]+(_[0-9a-f]+)?\b", "vXXX"),
  (r"\b[a-z]*Stack_[0-9a-f]+\b", "vXXX"),
  (r"\bparam_[0-9]+\b", "aXXX"),
]

# Prefixes of mangled names (MSVC, Itanium, Borland, etc...)
MANGLED_PREFIXES = ("?", "_Z", "__Z", "@")

LOG_PREFIX = "[Diaphora]"

#-------------------------------------------------------------------------------
# The current GhidraScript (if any) used to print messages and to update the
# progress of the task monitor.
g_script = None
g_monitor = None
g_main_thread = None

def set_script(script, monitor=None):
  """
  Register the GhidraScript that is running Diaphora, used for logging and for
  reporting progress and handling cancellations.
  """
  global g_script, g_monitor, g_main_thread
  g_script = script
  g_monitor = monitor
  g_main_thread = threading.current_thread().ident

  # Redirect the messages of the diffing engine to the Ghidra's console
  diaphora.log = log
  diaphora.log_refresh = log_refresh

#-------------------------------------------------------------------------------
def log(message):
  line = f"{LOG_PREFIX} {time.asctime()}: {message}"
  try:
    # In headless mode println() only goes to the log file, not to stdout
    if g_script is not None and not g_script.isRunningHeadless():
      g_script.println(line)
      return
  except: # noqa: S110
    pass
  print(line, flush=True)

#-------------------------------------------------------------------------------
def log_refresh(message, show=False, do_log=True):
  """
  Print a message, update the task monitor and, as a side effect, check if the
  user cancelled the task (only for the thread running the script).
  """
  if do_log:
    log(message)

  if g_monitor is not None and threading.current_thread().ident == g_main_thread:
    try:
      g_monitor.setMessage(str(message).split("\n")[0])
    except: # noqa: S110
      pass

    if g_monitor.isCancelled():
      raise CDiaphoraCancelled("Cancelled by the user.")

#-------------------------------------------------------------------------------
def debug_refresh(message):
  if diaphora.is_debug_enabled():
    log(message)

#-------------------------------------------------------------------------------
class CDiaphoraCancelled(Exception):
  """
  Raised when the user cancels the current export or diffing task.
  """

#-------------------------------------------------------------------------------
def translate_ghidra_names(text):
  """
  Translate Ghidra's default symbol names to IDA's ones (FUN_ -> sub_, LAB_ ->
  loc_, DAT_ -> unk_, etc...).
  """
  if text is None or text == "":
    return text

  text = GHIDRA_DEFAULT_NAME_RE.sub(lambda m: GHIDRA_DEFAULT_PREFIXES[m.group(1)], text)
  text = GHIDRA_POINTER_NAME_RE.sub("off_", text)
  text = GHIDRA_STRING_NAME_RE.sub(lambda m: "a" + m.group(1).replace("_", ""), text)
  return text

#-------------------------------------------------------------------------------
def to_unsigned(value):
  return int(value) & 0xFFFFFFFFFFFFFFFF

#-------------------------------------------------------------------------------
class CGhidraBinDiff(diaphora.CBinDiff):
  """
  The main binary diffing class for Ghidra.
  """

  def __init__(self, db_name, program=None, monitor=None, chooser=diaphora.CChooser):
    diaphora.CBinDiff.__init__(self, db_name, chooser=chooser)
    self.program = program
    self.monitor = monitor if monitor is not None else TaskMonitor.DUMMY
    self.decompiler_available = config.EXPORTING_USE_DECOMPILER
    self.decompiler = None
    self.project_script = None
    self.hooks = None

    # Callback used to ask questions to the user (None when running headless)
    self.ask_yes_no = None

    self.switches_cache = {}
    self.microcode_bblocks_cache = {}
    self.microcode_ins_list = self.get_microcode_instructions()

    # Exported function names and their addresses, see get_unique_name()
    self.exported_names = {}

    if program is not None:
      self.listing = program.getListing()
      self.memory = program.getMemory()
      self.refman = program.getReferenceManager()
      self.symtab = program.getSymbolTable()
      self.funcman = program.getFunctionManager()
      self.equates = program.getEquateTable()
      self.block_model = BasicBlockModel(program)
      self.image_base = program.getImageBase().getUnsignedOffset()
      self.space = program.getAddressFactory().getDefaultAddressSpace()
      self.min_ea, self.max_ea = self.get_loaded_range()

      options = CodeUnitFormatOptions(
        CodeUnitFormatOptions.ShowBlockName.NEVER,
        CodeUnitFormatOptions.ShowNamespace.NEVER
      )
      self.cuf = CodeUnitFormat(options)

  def open_db(self):
    """
    Open the database @self.db_name. Ghidra scripts don't run in the Python's
    main thread, so the first opened database is considered the main one.
    """
    db = diaphora.sqlite3_connect(self.db_name)

    tid = threading.current_thread().ident
    self.dbs_dict[tid] = db
    if self.db is None:
      self.db = db
      self.create_schema()

  def db_close(self):
    """
    Close the database opened for the current thread.
    """
    tid = threading.current_thread().ident
    if tid in self.dbs_dict:
      db = self.dbs_dict[tid]
      del self.dbs_dict[tid]
      if db is self.db:
        self.db = None
      db.close()

    if self.db is not None and len(self.dbs_dict) == 0:
      self.db.close()
      self.db = None

  def log(self, message):
    log(message)

  def log_refresh(self, message):
    log_refresh(message)

  def get_loaded_range(self):
    """
    Return the minimum and maximum addresses of the loaded memory blocks in the
    default address space, excluding the fake EXTERNAL block.
    """
    min_ea = None
    max_ea = None
    for block in self.memory.getBlocks():
      if not block.isLoaded() or block.isExternalBlock():
        continue
      if block.getStart().getAddressSpace() != self.space:
        continue

      start = block.getStart().getUnsignedOffset()
      end = block.getEnd().getUnsignedOffset()
      min_ea = start if min_ea is None else min(min_ea, start)
      max_ea = end if max_ea is None else max(max_ea, end)

    if min_ea is None:
      min_ea = self.program.getMinAddress().getUnsignedOffset()
      max_ea = self.program.getMaxAddress().getUnsignedOffset()
    return min_ea, max_ea

  def clear_pseudo_fields(self):
    self.pseudo = {}
    self.pseudo_hash = {}
    self.pseudo_comments = {}
    self.microcode = {}
    self.switches_cache = {}
    self.microcode_bblocks_cache = {}

  def equal_db(self):
    are_equal = diaphora.CBinDiff.equal_db(self)
    if are_equal and self.ask_yes_no is not None:
      msg = "The databases seems to be 100% equal. Do you want to continue anyway?"
      if not self.ask_yes_no("Diaphora", msg):
        self.do_continue = False
    return are_equal

  #-----------------------------------------------------------------------------
  # Text cleaning routines
  #-----------------------------------------------------------------------------
  def get_cmp_asm(self, asm):
    if asm is None:
      return asm

    for rep, repl in GHIDRA_CLEAN_ASM_REPS:
      asm = self.re_sub(rep, repl, asm)
    return diaphora.CBinDiff.get_cmp_asm(self, asm)

  def get_cmp_pseudo_lines(self, pseudo):
    if pseudo is None:
      return pseudo

    for rep, repl in GHIDRA_CLEAN_PSEUDO_REPS:
      pseudo = self.re_sub(rep, repl, pseudo)
    return diaphora.CBinDiff.get_cmp_pseudo_lines(self, pseudo)

  #-----------------------------------------------------------------------------
  # Address and symbol helpers
  #-----------------------------------------------------------------------------
  def get_base_address(self):
    return self.image_base

  def to_addr(self, ea):
    return self.space.getAddress(int(ea))

  def get_symbol_name(self, addr, include_defaults=True):
    """
    Return the (translated) name of the primary symbol at @addr, if any.
    """
    sym = self.symtab.getPrimarySymbol(addr)
    if sym is None:
      return None
    if not include_defaults and sym.getSource() == SourceType.DEFAULT:
      return None
    return translate_ghidra_names(sym.getName())

  def get_type_at(self, addr):
    """
    Return the type (as a C string) of the function or data item at @addr.
    """
    func = self.funcman.getFunctionAt(addr)
    if func is not None:
      if func.getSignatureSource() == SourceType.DEFAULT:
        return None
      return translate_ghidra_names(func.getPrototypeString(False, False))

    data = self.listing.getDataAt(addr)
    if data is not None and data.isDefined():
      return data.getDataType().getDisplayName()
    return None

  def get_string_at(self, addr):
    data = self.listing.getDataAt(addr)
    if data is not None and data.hasStringValue():
      value = data.getValue()
      if value is not None:
        return str(value)
    return None

  def get_function_names(self, func):
    """
    Return the 3 different names that a function might have: the name that we
    will show, the "true" (mangled, if available) name and the demangled name.
    """
    name = translate_ghidra_names(func.getName(True))
    true_name = None
    for sym in self.symtab.getSymbols(func.getEntryPoint()):
      sym_name = sym.getName()
      if sym_name.startswith(MANGLED_PREFIXES):
        true_name = sym_name
        break

    if true_name is None:
      return name, name, None
    return name, true_name, name

  def get_function_flags(self, func):
    """
    Emulate IDA's function flags used by Diaphora.
    """
    flags = 0
    if func.hasNoReturn():
      flags |= FUNC_NORET
    if func.isThunk():
      flags |= FUNC_THUNK
    for tag in func.getTags():
      if tag.getName().upper().find("LIBRARY") > -1:
        flags |= FUNC_LIB
        break
    return flags

  def get_function_comment(self, func):
    comment = func.getComment()
    if comment is None:
      comment = func.getRepeatableComment()
    return comment

  #-----------------------------------------------------------------------------
  # Decompiler support
  #-----------------------------------------------------------------------------
  def get_decompiler(self):
    if self.decompiler is None:
      iface = DecompInterface()
      options = DecompileOptions()
      options.grabFromProgram(self.program)
      iface.setOptions(options)
      iface.toggleCCode(True)
      iface.toggleSyntaxTree(True)
      iface.setSimplificationStyle("decompile")
      if not iface.openProgram(self.program):
        log(f"Error initializing the decompiler: {iface.getLastMessage()}")
        self.decompiler_available = False
        return None
      self.decompiler = iface
    return self.decompiler

  def dispose_decompiler(self):
    if self.decompiler is not None:
      self.decompiler.dispose()
      self.decompiler = None

  def get_microcode_instructions(self):
    """
    Ghidra's high level P-Code is exported as Diaphora's "microcode".
    """
    instructions = set()
    for i in range(PcodeOp.PCODE_MAX):
      try:
        instructions.add(str(PcodeOp.getMnemonic(i)).lower())
      except: # noqa: S110
        pass
    return sorted(instructions)

  def format_varnode(self, vn):
    if vn is None:
      return "_"

    size = vn.getSize()
    if vn.isConstant():
      return "#0x%x.%d" % (to_unsigned(vn.getOffset()), size)

    addr = vn.getAddress()
    if vn.isRegister():
      reg = self.program.getRegister(addr, size)
      if reg is None:
        reg = self.program.getRegister(addr)
      if reg is not None:
        return f"{reg.getName()}.{size}"
      return f"reg_{addr.getOffset():x}.{size}"

    if vn.isUnique():
      return f"tmp.{size}"

    if addr.isStackAddress():
      return f"stk_{addr.getOffset():x}.{size}"

    if vn.isAddress():
      name = self.get_symbol_name(addr)
      if name is None:
        name = "0x%x" % addr.getUnsignedOffset()
      return f"[{name}].{size}"

    return f"{addr}.{size}"

  def get_microcode(self, high):
    """
    Build the "microcode" basic blocks, relations and lines from Ghidra's high
    level P-Code of the decompiled function.
    """
    bblocks = {}
    bb_relations = {}
    lines = []
    for block in high.getBasicBlocks():
      index = block.getIndex()
      new_lines = []
      num = 0
      it = block.getIterator()
      while it.hasNext():
        op = it.next()
        mnem = str(op.getMnemonic()).lower()
        inputs = [self.format_varnode(vn) for vn in op.getInputs()]
        line = f"{mnem} {', '.join(inputs)}".strip()
        if op.getOutput() is not None:
          line += f" => {self.format_varnode(op.getOutput())}"

        line_ea = op.getSeqnum().getTarget().getUnsignedOffset()
        new_lines.append({
          "address": line_ea,
          "line": line,
          "mnemonic": mnem,
          "color_line": line,
          "comments": None,
        })
        lines.append(f"{index}.{num} {line}")
        num += 1

      start = block.getStart()
      start_ea = start.getUnsignedOffset() if start is not None else 0
      bblocks[index] = {"start": start_ea, "lines": new_lines}

      for i in range(block.getOutSize()):
        succ = block.getOut(i).getIndex()
        try:
          bb_relations[index].append(succ)
        except KeyError:
          bb_relations[index] = [succ]

    return bblocks, bb_relations, lines

  def decompile_and_get(self, ea):
    """
    Decompile the function at @ea and return its prototype (the first line of
    the pseudo-code). The pseudo-code, its AST-like hash, switches and P-Code
    are stored in the corresponding caches.
    """
    if not self.decompiler_available:
      return False

    iface = self.get_decompiler()
    if iface is None:
      return False

    func = self.funcman.getFunctionAt(self.to_addr(ea))
    if func is None:
      return False

    res = iface.decompileFunction(func, config.GHIDRA_DECOMPILER_TIMEOUT, self.monitor)
    if res is None or not res.decompileCompleted():
      return False

    dfunc = res.getDecompiledFunction()
    high = res.getHighFunction()
    if dfunc is None or high is None:
      return False

    # Our replacement for the Hex-Rays' ctree visitor: the product of the primes
    # assigned to every high level P-Code operation.
    primes_hash = 1
    for op in high.getPcodeOps():
      primes_hash *= self.primes[op.getOpcode()]
    self.pseudo_hash[ea] = primes_hash

    proto_lines = []
    body = []
    for line in str(dfunc.getC()).split("\n"):
      line = line.rstrip()
      tmp = line.strip()
      if tmp == "" or tmp.startswith("//"):
        continue
      if tmp.startswith("/*") and tmp.endswith("*/"):
        continue

      line = translate_ghidra_names(line)
      if len(body) == 0 and tmp != "{":
        proto_lines.append(tmp)
      else:
        body.append(line)

    if len(body) == 0:
      # Weird output, just use whatever we got
      body = proto_lines
      proto_lines = [translate_ghidra_names(str(dfunc.getSignature()))]

    self.pseudo[ea] = body

    switches = []
    for jump_table in high.getJumpTables():
      cases = jump_table.getCases()
      labels = set()
      for label in jump_table.getLabelValues():
        labels.add(int(label))
      switches.append([len(cases), sorted(labels)])
    self.switches_cache[ea] = switches

    if self.export_microcode:
      bblocks, bb_relations, lines = self.get_microcode(high)
      self.microcode[ea] = lines
      self.microcode_bblocks_cache[ea] = (bblocks, bb_relations)

    return " ".join(proto_lines)

  def guess_type(self, func, ea):
    proto = translate_ghidra_names(func.getPrototypeString(False, False))
    if self.use_decompiler:
      try:
        ret = self.decompile_and_get(ea)
        if ret:
          proto = ret
      except CDiaphoraCancelled:
        raise
      except:
        log("Cannot decompile 0x%x: %s" % (ea, str(sys.exc_info()[1])))
    return proto

