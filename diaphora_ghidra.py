  def get_last_crash_func(self):
    """
    Get the last inserted row before Ghidra or Diaphora crashed.
    """
    sql = "select address from functions order by id desc limit 1"
    cur = self.db_cursor()
    try:
      cur.execute(sql)
      row = cur.fetchone()
      if not row:
        return None
      address = int(row[0])
    finally:
      cur.close()
    return address

  def recalculate_primes(self):
    """
    Recalculate the primes assigned to a function.
    """
    sql = "select primes_value from functions"

    callgraph_primes = 1
    callgraph_all_primes = {}

    cur = self.db_cursor()
    try:
      cur.execute(sql)
      for row in cur.fetchall():
        ret = row[0]
        callgraph_primes *= decimal.Decimal(row[0])
        try:
          callgraph_all_primes[ret] += 1
        except KeyError:
          callgraph_all_primes[ret] = 1
    finally:
      cur.close()

    return callgraph_primes, callgraph_all_primes

  def commit_and_start_transaction(self):
    try:
      self.db.execute("commit")
    except sqlite3.OperationalError:
      # Ignore the "cannot commit - no transaction active" error
      pass

    if config.SQLITE_PRAGMA_SYNCHRONOUS is not None:
      self.db.execute(f"PRAGMA synchronous = {config.SQLITE_PRAGMA_SYNCHRONOUS}")
    if config.SQLITE_JOURNAL_MODE is not None:
      self.db.execute(f"PRAGMA journal_mode = {config.SQLITE_JOURNAL_MODE}")
    self.db.execute("BEGIN transaction")

  def get_functions_list(self):
    """
    Return the sorted list of addresses of the functions to export.
    """
    ret = []
    for func in self.funcman.getFunctions(True):
      if func.isExternal():
        continue
      ea = func.getEntryPoint().getUnsignedOffset()
      if self.min_ea <= ea <= self.max_ea:
        ret.append(ea)
    return ret

  def get_processor_name(self):
    """
    Return the processor name using, when possible, the same naming that the
    IDA exporter uses.
    """
    language = self.program.getLanguage()
    processor = str(language.getProcessor())
    names = {"x86": "metapc", "ARM": "arm", "AARCH64": "arm", "MIPS": "mips",
             "PowerPC": "ppc", "Sparc": "sparc", "68000": "68k"}
    proc = names.get(processor, processor.lower())
    if self.program.getDefaultPointerSize() == 8:
      proc += "64"
    return proc

  def save_callgraph(self, primes, all_primes, md5sum):
    cur = self.db_cursor()
    try:
      sql = "insert into main.program (callgraph_primes, callgraph_all_primes, processor, md5sum) values (?, ?, ?, ?)"
      cur.execute(sql, (primes, all_primes, self.get_processor_name(), md5sum))
    finally:
      cur.close()

  def do_export(self, crashed_before=False):
    """
    Internal use, export the database.
    """
    callgraph_primes = 1
    callgraph_all_primes = {}
    log("Exporting range 0x%08x - 0x%08x" % (self.min_ea, self.max_ea))
    func_list = self.get_functions_list()
    total_funcs = len(func_list)
    t = time.monotonic()

    start_func = None
    if crashed_before:
      start_func = self.get_last_crash_func()
      if start_func is None:
        log("Diaphora cannot resume the previous crashed session, the export process will start from scratch.")
        crashed_before = False
      else:
        callgraph_primes, callgraph_all_primes = self.recalculate_primes()
        self.load_exported_names()

    self.monitor.initialize(total_funcs)
    self.commit_and_start_transaction()

    i = 0
    self._funcs_cache = {}
    checkpoint = max(int(total_funcs / 100), 1)
    for func in func_list:
      self.monitor.checkCancelled()

      i += 1
      self.monitor.setProgress(i)
      if i % checkpoint == 0 or i == 1:
        if config.COMMIT_AFTER_EACH_GUI_UPDATE:
          self.commit_and_start_transaction()
        elapsed = time.monotonic() - t
        remaining = (elapsed / i) * (total_funcs - i)
        line = "Exported %d function(s) out of %d total, remaining time ~%s"
        self.monitor.setMessage(
          line % (i, total_funcs, datetime.timedelta(seconds=int(remaining)))
        )

      if crashed_before:
        if func != start_func:
          continue

        # When we get to the last function that was previously exported, switch
        # off the 'crash' flag and continue with the next row.
        crashed_before = False
        continue

      try:
        props = self.read_function(func)
      except (CDiaphoraCancelled, CancelledException):
        raise
      except:
        log("Error exporting function 0x%x: %s" % (func, str(sys.exc_info()[1])))
        traceback.print_exc()
        props = False
      self.clear_pseudo_fields()
      if props is False:
        continue

      ret = props[11]
      callgraph_primes *= decimal.Decimal(ret)
      try:
        callgraph_all_primes[ret] += 1
      except KeyError:
        callgraph_all_primes[ret] = 1

      self.save_function(props)

      if total_funcs > config.EXPORTING_FUNCTIONS_TO_COMMIT:
        if i % (total_funcs / 10) == 0:
          self.commit_and_start_transaction()

    self.commit_and_start_transaction()
    md5sum = self.program.getExecutableMD5()
    self.save_callgraph(
      str(callgraph_primes), json.dumps(callgraph_all_primes), md5sum
    )

    log_refresh("Creating indices...")
    self.create_indices()

  def is_database_ok(self):
    """
    Check if the database from a crashed export can still be used.
    """
    cur = self.db_cursor()
    try:
      cur.execute("pragma quick_check")
      row = cur.fetchone()
    except sqlite3.DatabaseError:
      return False
    finally:
      cur.close()

    return row is not None and row[0] == "ok"

  def recreate_database(self):
    """ Remove the current database and surviving files and create a new one
    """
    self.db_close()
    for suffix in ["", "-wal", "-shm"]:
      filename = f"{self.db_name}{suffix}"
      if os.path.exists(filename):
        os.remove(filename)
    self.open_db()

  def load_exported_names(self):
    """
    Load the names of the functions already exported (when resuming a crashed
    export session).
    """
    cur = self.db_cursor()
    try:
      cur.execute("select name, mangled_function, address from functions")
      for row in cur.fetchall():
        self.exported_names[row["name"]] = int(row["address"])
        self.exported_names[row["mangled_function"]] = int(row["address"])
    finally:
      cur.close()

  def export(self):
    """
    Export the current database. Call script hooks if there is any.
    """
    if self.project_script is not None:
      if not self.load_hooks():
        return False

    crashed_before = False
    crash_file = f"{self.db_name}-crash"
    if os.path.exists(crash_file):
      if self.is_database_ok():
        log("Resuming a previously crashed session...")
        crashed_before = True
      else:
        log("The database from the crashed session is broken, exporting from scratch...")
        self.recreate_database()

    log(f"Creating crash file {crash_file}...")
    with open(crash_file, "wb") as f:
      f.close()

    try:
      self.do_export(crashed_before)
    except (CDiaphoraCancelled, CancelledException):
      # Keep the crash file, so the export can be resumed later
      raise
    except:
      log(f"Error: {str(sys.exc_info()[1])}")
      traceback.print_exc()
      if self.hooks is not None and "on_export_crash" in dir(self.hooks):
        if not self.hooks.on_export_crash():
          raise
      self.db_close()
      return False
    finally:
      self.dispose_decompiler()

    self.db.commit()
    log(f"Removing crash file {self.db_name}-crash...")
    os.remove(f"{self.db_name}-crash")

    cur = self.db_cursor()
    try:
      cur.execute("analyze")
    finally:
      cur.close()

    self.db_close()
    return True

