  def reinit(self, main_db, diff_db):
    """
    Reinitialize databases.
    """
    log(f"Main database '{main_db}'.")
    log(f"Diff database '{diff_db}'.")

    chooser = self.chooser
    self.db_close()
    diaphora.CBinDiff.__init__(self, main_db, chooser=chooser)
    self.attach_database(diff_db)
    self.last_diff_db = diff_db

  def populate_choosers(self, cur, min_ratio=None, multimatch=True):
    cur.execute("select * from results")
    for row in diaphora.result_iter(cur):
      rtype = row["type"]
      if rtype == "best":
        choose = self.best_chooser
      elif rtype == "partial":
        choose = self.partial_chooser
      elif rtype == "multimatch" and multimatch:
        choose = self.multimatch_chooser
      else:
        choose = self.unreliable_chooser

      ratio = float(row["ratio"])
      if min_ratio is not None and ratio < min_ratio:
        continue

      choose.add_item(
        diaphora.CChooser.Item(
          int(row["address"], 16), row["name"],
          int(row["address2"], 16), row["name2"],
          row["description"], ratio,
          int(row["nodes1"]), int(row["nodes2"]),
        )
      )

    cur.execute("select * from unmatched")
    for row in diaphora.result_iter(cur):
      if row["type"] == "primary":
        choose = self.unmatched_primary
      else:
        choose = self.unmatched_second

      item = diaphora.CChooser.Item(int(row["address"], 16), row["name"])
      choose.add_item(item)

  def load_results(self, filename, ask_file=None):
    """
    Load the diffing results previously saved in @filename. The callback
    @ask_file is used to ask for the databases' paths if they don't exist.
    """
    results_db = diaphora.sqlite3_connect(filename)

    cur = results_db.cursor()
    try:
      cur.execute("select main_db, diff_db, version from config")
      rows = cur.fetchall()
      if len(rows) != 1:
        log("Malformed results database!")
        return False

      row = rows[0]
      version = row["version"]
      if version != diaphora.VERSION_VALUE:
        log(
          f"The version of the diff results is {version} and current version is {diaphora.VERSION_VALUE}, there can be some incompatibilities."
        )

      main_db = row["main_db"]
      diff_db = row["diff_db"]
      if not os.path.exists(main_db):
        log(f"Primary database {main_db} not found.")
        if ask_file is None:
          return False
        main_db = ask_file("Select the primary database path", main_db)
        if main_db is None:
          return False

      if not os.path.exists(diff_db):
        log(f"Secondary database {diff_db} not found.")
        if ask_file is None:
          return False
        diff_db = ask_file("Select the secondary database path", diff_db)
        if diff_db is None:
          return False

      self.reinit(main_db, diff_db)
      self.populate_choosers(cur)
    finally:
      cur.close()
      results_db.close()

    return True

