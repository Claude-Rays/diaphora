  def get_import_name(self, row):
    """
    Return the name to import from a row of the secondary database, or None if
    the name is an auto-generated one.
    """
    name = row["name"]
    mangled = row["mangled_function"]
    if name is None or self.is_auto_generated(name):
      return None

    # Databases exported with IDA use the demangled function prototype as name
    if name.find("(") > -1 or name.find(" ") > -1:
      if mangled is None or self.is_auto_generated(mangled):
        return None
      name = mangled
    return name

  def set_function_name(self, func, name):
    """
    Set the name of the function @func, creating the namespaces if required.
    """
    # pylint: disable=import-error
    from ghidra.app.util import NamespaceUtils
    from ghidra.program.model.symbol import SymbolUtilities
    # pylint: enable=import-error

    namespace = None
    short_name = name
    if not name.startswith(MANGLED_PREFIXES) and name.find("::") > -1:
      parts = name.split("::")
      short_name = parts[-1]
      try:
        namespace = NamespaceUtils.createNamespaceHierarchy(
          "::".join(parts[:-1]), None, self.program, SourceType.IMPORTED
        )
      except:
        namespace = None
        short_name = name

    short_name = SymbolUtilities.replaceInvalidChars(short_name, True)
    for i in range(10):
      new_name = short_name if i == 0 else f"{short_name}_{i}"
      try:
        if namespace is not None:
          func.setParentNamespace(namespace)
        func.setName(new_name, SourceType.IMPORTED)
        return True
      except: # noqa: S112
        continue
    return False

  def do_import_one(self, ea1, ea2, force=False):
    """
    Import the name and comment of the function at @ea2 in the secondary
    database into the function at @ea1 in the current program.
    """
    cur = self.db_cursor()
    try:
      sql = "select name, prototype, comment, mangled_function from diff.functions where address = ?"
      cur.execute(sql, (str(ea2),))
      row = cur.fetchone()
    finally:
      cur.close()

    if row is None:
      return False

    func = self.funcman.getFunctionAt(self.to_addr(ea1))
    if func is None:
      return False

    name = self.get_import_name(row)
    if name is None and force:
      name = row["mangled_function"] or row["name"]

    if name is not None and func.getName(True) != name:
      self.set_function_name(func, name)

    comment = row["comment"]
    if comment is not None and comment != "" and func.getComment() is None:
      func.setComment(comment)
    return True

  def import_items(self, items, force=False):
    """
    Import the names and comments of a list of (ea1, ea2) pairs inside a single
    Ghidra transaction and update the primary database.
    """
    total = 0
    tx = self.program.startTransaction("Diaphora: import results")
    try:
      for ea1, ea2 in items:
        if self.do_import_one(ea1, ea2, force):
          total += 1
    finally:
      self.program.endTransaction(tx, True)

    # Update the main database with the new information of the functions. The
    # task monitor of the script that created us is already gone.
    old_monitor = self.monitor
    self.monitor = TaskMonitor.DUMMY
    try:
      for ea1, _ in items:
        new_func = self.read_function(ea1)
        self.clear_pseudo_fields()
        if new_func:
          self.delete_function(ea1)
          self.save_function(new_func)
      self.get_db().commit()
    finally:
      self.dispose_decompiler()
      self.monitor = old_monitor

    log(f"{total} function(s) imported.")
    return total

