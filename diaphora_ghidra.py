def get_default_database_name(program):
  """
  Return the default path for the exported database of @program. As the IDA
  exporter does with the IDB's directory, it's the directory of the project that
  contains the program.
  """
  directory = None
  name = program.getName()
  try:
    # The name of the program in the project, like the IDB's file name
    name = str(program.getDomainFile().getName())
    locator = program.getDomainFile().getProjectLocator()
    if locator is not None and not locator.isTransient():
      # The directory of the .gpr file (getLocation() returns an URL like path)
      directory = str(locator.getMarkerFile().getParentFile().getAbsolutePath())
  except:
    directory = None

  if directory is None or not os.path.isdir(directory):
    directory = os.path.expanduser("~")

  return os.path.join(directory, f"{name}.sqlite")

