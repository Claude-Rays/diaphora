  def read_function(self, ea):
    """Extract anything and everything we (might) need from a function."""
    f = int(ea)
    func = self.funcman.getFunctionAt(self.to_addr(f))
    if func is None:
      log("Cannot get a function object for 0x%x" % f)
      return False

    name, true_name, _ = self.get_function_names(func)

    # Call hooks immediately after we have a proper function name
    if not self.run_pre_export_hook(f, name):
      return False

    should_skip, skip_reason = self.should_skip_function(func, name)
    if should_skip:
      debug_refresh(skip_reason)
      return False

    if true_name == name:
      name = true_name = self.get_unique_name(name, f)
    else:
      name = self.get_unique_name(name, f)
      true_name = self.get_unique_name(true_name, f)

    data = self.initialize_function_data(func)
    image_base = data["image_base"]
    for block in data["flow"]:
      data = self.process_basic_block(block, func, image_base, data)

    data["bb_topological"] = self.build_topological_relations(
      data["flow"], image_base, data["bb_topo_num"], data["bb_topological"]
    )

    features = self.extract_all_features(f, func, data)
    props_list = self.build_props_list(name, true_name, f, data, features)
    props_list = self.run_post_export_hook(props_list)
    return props_list

